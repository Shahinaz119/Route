"""End-to-end pipeline: CV -> profile -> gaps -> course recommendations -> roadmap.

Examples:
  # Full run with a raw CV (needs build_llm() implemented)
  python src/pipeline.py --cv data/cv.pdf --role junior_ai_engineer \
      --roles data/roles_sample.json --catalog data/your_catalog.json

  # Run with a hand-labeled profile (no LLM needed)
  python src/pipeline.py --cv-profile data/profile.json --role junior_ai_engineer \
      --roles data/roles_sample.json --catalog data/your_catalog.json
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from pydantic import TypeAdapter

from catalog import load_catalog, load_tags
from course_matcher import match_courses
from cv_extractor import LLMClient, extract_profile, read_cv_text
from gap_analyzer import analyze_gaps
from models import CatalogCourse, CourseTags, CVProfile, RoleProfile

DEFAULT_TAGS_PATH = Path("data/course_skill_tags.json")

LIMITATIONS = [
    "The catalog has no levels or prerequisites, so the roadmap is ordered by gap priority, not by learning sequence.",
    "Course skills are generated by an LLM from catalog text and count only after human review.",
    "Matching uses exact normalized skill names, so semantically close skills may be missed.",
    "Unverified skills are reported for the candidate to prove and do not trigger recommendations.",
    "Stage, duration and certificate hours are shown as information only and do not affect matching.",
]


def load_roles(path: Path) -> dict[str, RoleProfile]:
    data = json.loads(path.read_text(encoding="utf-8"))
    roles = TypeAdapter(list[RoleProfile]).validate_python(data)
    return {role.role_id: role for role in roles}


def build_llm() -> LLMClient:
    """Return the Gemini client. Reads GOOGLE_API_KEY from the environment."""
    from llm_gemini import GeminiClient

    return GeminiClient()


def build_report(
    cv: CVProfile,
    role: RoleProfile,
    courses: list[CatalogCourse],
    catalog_stats: dict,
    tags: dict,
    extra_warnings: list[str],
) -> dict:
    gaps = analyze_gaps(cv, role)
    return {
        "role": role.title,
        "role_source": role.source,
        "candidate_skills": [
            s.model_dump(mode="json", exclude={"source_quote"}) for s in cv.skills
        ],
        "gaps": [g.model_dump(mode="json") for g in gaps],
        "unverified": [g.skill for g in gaps if g.status == "unverified"],
        # Roadmap is now built by the agent using match_catalog_courses per gap.
        "roadmap": [],
        "uncovered_gaps": [],
        "catalog": catalog_stats,
        "warnings": extra_warnings,
        "limitations": LIMITATIONS,
    }


def run(
    role_id: str,
    roles_path: Path,
    catalog_path: Path,
    tags_path: Path = DEFAULT_TAGS_PATH,
    cv_path: Path | None = None,
    cv_profile_path: Path | None = None,
    llm: LLMClient | None = None,
) -> dict:
    roles = load_roles(roles_path)
    if role_id not in roles:
        raise KeyError(f"Unknown role_id {role_id!r}. Available: {sorted(roles)}")

    courses, catalog_stats = load_catalog(catalog_path)
    tags = load_tags(tags_path)
    extra_warnings: list[str] = []
    if not tags_path.exists():
        extra_warnings.append(f"Tags file {tags_path} not found. Run tag_courses.py first.")

    if cv_profile_path is not None:
        cv = CVProfile.model_validate_json(cv_profile_path.read_text(encoding="utf-8"))
    elif cv_path is not None:
        if llm is None:
            raise ValueError("An LLMClient is required when extracting from a raw CV")
        cv = extract_profile(read_cv_text(cv_path), llm)
    else:
        raise ValueError("Provide either a CV file or a pre-extracted profile")

    return build_report(cv, roles[role_id], courses, catalog_stats, tags, extra_warnings)


def render_markdown(report: dict) -> str:
    stats = report["catalog"]
    lines = [
        f"# Learning roadmap: {report['role']}",
        "",
        f"Catalog: {stats['published']} published courses (of {stats['total_rows']} rows, "
        f"{stats['skipped_unpublished']} unpublished skipped, {len(stats['invalid_rows'])} invalid).",
        "",
        "## Recommended courses",
    ]
    if report["roadmap"]:
        for step, item in enumerate(report["roadmap"], start=1):
            lines.append(f"{step}. **{item['title']}** ({item['delivery_type']}): {item['reason']}")
    else:
        lines.append("No course recommendations were produced.")

    lines += ["", "## Gaps not covered by the catalog"]
    lines.extend(f"- {skill}" for skill in report["uncovered_gaps"] or ["None"])

    lines += ["", "## Skills to verify (listed but not demonstrated)"]
    lines.extend(f"- {skill}" for skill in report["unverified"] or ["None"])

    if report["warnings"]:
        lines += ["", "## Warnings"]
        lines.extend(f"- {w}" for w in report["warnings"])

    lines += ["", "## Limitations"]
    lines.extend(f"- {item}" for item in report["limitations"])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Smart Career Path & Skill Gap Agent")
    parser.add_argument("--role", required=True, help="role_id from the roles file")
    parser.add_argument("--roles", type=Path, required=True)
    parser.add_argument("--catalog", type=Path, required=True)
    parser.add_argument("--tags", type=Path, default=DEFAULT_TAGS_PATH)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--cv", type=Path, help="raw CV (.pdf, .txt, .md); uses the LLM")
    source.add_argument("--cv-profile", type=Path, help="pre-extracted CVProfile JSON; no LLM")
    parser.add_argument("--out", type=Path, default=Path("report.json"))
    args = parser.parse_args()

    llm = build_llm() if args.cv is not None else None
    report = run(
        role_id=args.role,
        roles_path=args.roles,
        catalog_path=args.catalog,
        tags_path=args.tags,
        cv_path=args.cv,
        cv_profile_path=args.cv_profile,
        llm=llm,
    )
    args.out.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(render_markdown(report))


if __name__ == "__main__":
    main()